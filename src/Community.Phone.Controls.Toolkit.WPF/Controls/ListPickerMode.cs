namespace Microsoft.Phone.Controls
{
    /// <summary>
    /// Defines the supported ListPicker modes.
    /// </summary>
    public enum ListPickerMode
    {
        /// <summary>Only the selected item is visible on the page.</summary>
        Normal,
        /// <summary>All items are visible on the page.</summary>
        Expanded,
        /// <summary>All items are visible in a separate popup.</summary>
        Full
    }
}
