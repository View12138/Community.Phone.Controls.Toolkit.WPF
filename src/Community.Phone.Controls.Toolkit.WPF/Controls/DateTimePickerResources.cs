using Microsoft.Phone.Controls.LocalizedResources;

namespace Microsoft.Phone.Controls
{
    /// <summary>
    /// Provides localized strings used by the date/time pickers.
    /// </summary>
    public class DateTimePickerResources
    {
        /// <summary>
        /// Gets the date picker title.
        /// </summary>
        public static string DatePickerTitle
        {
            get { return ControlResources.DatePickerTitle; }
        }

        /// <summary>
        /// Gets the time picker title.
        /// </summary>
        public static string TimePickerTitle
        {
            get { return ControlResources.TimePickerTitle; }
        }
    }
}
