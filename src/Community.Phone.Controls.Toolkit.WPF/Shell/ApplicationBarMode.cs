namespace Microsoft.Phone.Shell
{
    /// <summary>
    /// Describes how the application bar is displayed.
    /// </summary>
    public enum ApplicationBarMode
    {
        /// <summary>
        /// The application bar shows the icon buttons and the menu button.
        /// </summary>
        Default,

        /// <summary>
        /// The application bar is collapsed to a thin strip that only shows the menu button.
        /// </summary>
        Minimized,
    }
}
